#!/usr/bin/env bash
# Puts this project under git and, if the GitHub CLI is available and signed
# in, creates the repository and pushes it. Safe to run more than once.
#
#   Scripts/init_repo.sh                  private repo named boat-race
#   Scripts/init_repo.sh my-name public   public repo with a different name
set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PROJECT_DIR"

REPO_NAME="${1:-boat-race}"
VISIBILITY="${2:-private}"

# ---------------------------------------------------------------------------
# What git should ignore. Unreal regenerates all of this, and the Higgsfield
# assets come back from Scripts/fetch_assets.sh, so none of it belongs in a
# repository. Without this you would be committing several GB.
# ---------------------------------------------------------------------------
cat > .gitignore <<'IGNORE'
# Unreal build output, all regenerated by Scripts/build.sh
Binaries/
Intermediate/
Saved/
DerivedDataCache/
Build/
.vs/
.vscode/
*.VC.db
*.opensdf
*.sdf
*.sln
*.suo
*.xcodeproj
*.xcworkspace

# Packaged builds
dist/

# Higgsfield source media: large, and Scripts/fetch_assets.sh downloads it
HiggsfieldAssets/*.png
HiggsfieldAssets/*.glb
HiggsfieldAssets/*.jpg
HiggsfieldAssets/*.mp4
*.part

# Imported Unreal assets, rebuilt by Scripts/import_assets.sh
Content/Higgsfield/*.uasset
Content/Higgsfield/*.umap

# Editor and OS leftovers
*~
.DS_Store
__pycache__/
*.pyc
IGNORE

# ---------------------------------------------------------------------------
# Who the commits belong to. Uses your existing git identity if you have one.
# ---------------------------------------------------------------------------
if ! git config user.name >/dev/null 2>&1 && ! git config --global user.name >/dev/null 2>&1; then
	echo "git does not know who you are yet. Set it with:"
	echo "    git config --global user.name  \"Your Name\""
	echo "    git config --global user.email \"you@example.com\""
	echo
	echo "If this will be a public repo, GitHub can give you a private address:"
	echo "Settings > Emails > 'Keep my email address private' shows a"
	echo "username@users.noreply.github.com you can use instead of a real one."
	exit 1
fi

if [ ! -d .git ]; then
	git init -q
	git branch -M main
	echo "Created a git repository here."
fi

git add -A
if git diff --cached --quiet; then
	echo "Nothing new to commit."
else
	git commit -q -m "Boat Race: four-player armed powerboat racing in Unreal Engine 5

A code-only UE5 project with no map or Blueprint assets: the sea, the circuit
and the scenery are all built at runtime in C++.

- Six-component wave field shared by the water mesh, the boats' buoyancy, the
  torpedoes and the floating crates, so what you see is what you hit
- Boats are 1200 kg rigid bodies floating on four buoyancy probes; planing,
  heeling and slamming all come out of the physics rather than animation
- 3 km, sixteen-gate circuit 90 m wide, with rock spires, jump ramps, moving
  barges, whirlpools and floating debris
- Server-authoritative torpedoes and mines; a wreck costs track position
- Listen-server networking for four players, with each player simulating their
  own boat and the host deciding laps and damage
- Art generated in Higgsfield, imported by Scripts/import_assets.sh
- Course layout and boat physics are both verified by scripts in Scripts/"
	echo "Committed $(git rev-list --count HEAD) revision(s)."
fi

echo
echo "Tracked files: $(git ls-files | wc -l)   Repository size: $(du -sh .git | cut -f1)"

# ---------------------------------------------------------------------------
# Push it to GitHub, if that is possible from here.
# ---------------------------------------------------------------------------
if git remote get-url origin >/dev/null 2>&1; then
	echo
	echo "Pushing to $(git remote get-url origin)"
	git push -u origin main
	exit 0
fi

if command -v gh >/dev/null 2>&1 && gh auth status >/dev/null 2>&1; then
	echo
	echo "Creating the $VISIBILITY GitHub repository '$REPO_NAME' and pushing."
	gh repo create "$REPO_NAME" "--$VISIBILITY" --source=. --remote=origin --push
	echo
	echo "Done: $(gh repo view --json url -q .url)"
else
	cat <<'NEXT'

The repository is committed locally. To put it on GitHub, either:

  1. Install and sign in to the GitHub CLI, then run this script again:
         sudo apt install gh && gh auth login

  2. Or create an empty repository at https://github.com/new (no README,
     no .gitignore, no licence), then run the two lines it shows you:
         git remote add origin https://github.com/YOUR-NAME/boat-race.git
         git push -u origin main
NEXT
fi
